import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';

test('Real HTTP account lifecycle: registration, private collection, conflict, logout and CORS', { timeout: 20000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'folia-http-'));
  const child = spawn(process.execPath, ['--experimental-strip-types', 'server.mjs'], { env: { ...process.env, API_PORT: '0', OPENAI_API_KEY: '', FOLIA_DB_PATH: join(dir, 'test.sqlite') }, stdio: ['ignore', 'pipe', 'pipe'] });
  try {
    const base = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Server start timeout')), 5000);
      child.on('exit', code => { clearTimeout(timer); reject(new Error(`Server exited ${code}`)); });
      child.stdout.on('data', data => { const match = data.toString().match(/http:\/\/0\.0\.0\.0:(\d+)/); if (match) { clearTimeout(timer); resolve(`http://127.0.0.1:${match[1]}`); } });
    });
    const request = (path, method = 'GET', token, body) => fetch(`${base}${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    const measure = await request('/measure', 'POST', undefined, {});
    assert.equal(measure.status, 401);
    assert.equal((await request('/identify', 'POST', undefined, {})).status, 401);
    assert.equal((await request('/delegations')).status, 401);
    assert.equal((await request('/delegations', 'POST', undefined, {})).status, 401);
    const malformed = await fetch(`${base}/measure`, { method: 'POST', body: '{' });
    assert.equal(malformed.status, 401);
    assert.equal((await request('/garden')).status, 401);
    const signup = await request('/auth/register', 'POST', undefined, { email: 'http@example.test', password: 'HTTP-test-password-123' });
    assert.equal(signup.status, 201);
    assert.equal(signup.headers.get('cache-control'), 'no-store');
    const session = await signup.json();
    const authenticatedMeasure = await request('/measure', 'POST', session.token, {});
    assert.equal(authenticatedMeasure.status, 503);
    assert.match((await authenticatedMeasure.json()).error, /OPENAI_API_KEY/);
    assert.equal((await fetch(`${base}/measure`, { method: 'POST', headers: { Authorization: `Bearer ${session.token}` }, body: '{' })).status, 400);
    const loaded = await (await request('/garden', 'GET', session.token)).json();
    assert.deepEqual(loaded, { garden: { plants: [], reminders: false }, revision: 0 });
    const caretaker = { name: 'Camille', phone: '+33 6 00 00 00 00', email: 'camille@example.test', notes: 'Vérifier le terreau avant d’arroser.' };
    const home = { version: 1, width: 12, height: 10, northAngle: 0, floor: 0, month: 6, latitude: 48.85, background: 'data:image/png;base64,YWJj', areas: [{ id: 'garden', name: 'Jardin', kind: 'garden', x: 0, y: 0, width: 4, height: 3, windows: [], shade: 'none' }] };
    const update = { garden: { plants: [], reminders: false, reminderTime: '08:45', caretaker, home }, revision: 0 };
    assert.equal((await request('/garden', 'PUT', session.token, update)).status, 200);
    assert.equal((await request('/garden', 'PUT', session.token, update)).status, 409);
    const options = await request('/garden', 'OPTIONS');
    assert.match(options.headers.get('access-control-allow-headers'), /Authorization/);
    assert.match(options.headers.get('access-control-allow-methods'), /PUT/);
    assert.equal((await request('/auth/logout', 'POST', session.token)).status, 200);
    assert.equal((await request('/garden', 'GET', session.token)).status, 401);
    const login = await request('/auth/login', 'POST', undefined, { email: 'http@example.test', password: 'HTTP-test-password-123' });
    assert.equal(login.status, 200);
    const again = await login.json();
    assert.equal((await (await request('/garden', 'GET', again.token)).json()).garden.reminderTime, '08:45');
    assert.deepEqual((await (await request('/garden', 'GET', again.token)).json()).garden.caretaker, caretaker);
    assert.deepEqual((await (await request('/garden', 'GET', again.token)).json()).garden.home, home);
    const invalidHome = await request('/garden', 'PUT', again.token, { garden: { ...update.garden, home: { ...home, width: -1 } }, revision: 1 });
    assert.equal(invalidHome.status, 400);
    assert.deepEqual((await (await request('/garden', 'GET', again.token)).json()).garden.home, home);
    const guest = await (await request('/auth/register', 'POST', undefined, { email: 'guest@example.test', password: 'HTTP-test-password-123' })).json();
    const plant = { id: 'shared', name: 'Aloe', species: 'Aloe vera', room: 'Salon', height: 30, pot: 14, soil: 'Terreau', temperature: 20, interval: 7, lastWatered: null, createdAt: '2026-09-01T12:00:00Z', repotDate: '2027-09-01T12:00:00Z', caretaker: '', history: [] };
    assert.equal((await request('/garden', 'PUT', again.token, { revision: 1, garden: { ...update.garden, plants: [plant] } })).status, 200);
    const invite = await request('/delegations', 'POST', again.token, { email: guest.user.email, startsAt: new Date(Date.now() - 1000).toISOString(), endsAt: new Date(Date.now() + 86400000).toISOString(), plantIds: [plant.id], notes: 'Consignes' });
    assert.equal(invite.status, 201);
    const created = await invite.json();
    assert.equal((await request('/delegations/accept', 'POST', guest.token, { invitation: created.invitation })).status, 200);
    const path = `/delegations/${created.delegation.id}`;
    assert.equal((await request(`${path}/garden`, 'GET', again.token)).status, 403);
    assert.equal((await (await request(`${path}/garden`, 'GET', guest.token)).json()).plants.length, 1);
    assert.equal((await request(`${path}/water`, 'POST', guest.token, { plantId: plant.id })).status, 200);
    assert.equal((await request(`${path}/revoke`, 'POST', again.token)).status, 200);
    assert.equal((await request(`${path}/water`, 'POST', guest.token, { plantId: plant.id })).status, 403);
    let limited;
    for (let i = 0; i < 21; i++) limited = await request('/auth/login', 'POST', undefined, { email: 'invalid', password: 'short' });
    assert.equal(limited.status, 429);
    for (let i = 0; i < 21; i++) limited = await request('/measure', 'POST', again.token, {});
    assert.equal(limited.status, 429);
  } finally { child.kill(); await once(child, 'exit'); await rm(dir, { recursive: true, force: true }); }
});
